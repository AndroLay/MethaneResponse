import { afterEach, describe, expect, test } from 'bun:test';
import { mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { isUnapprovedPublicAsset, isWithheldPublicAsset, pruneUnapprovedPublicAssets, WITHHELD_PUBLIC_ASSETS } from '../apps/web/build/withheld-public-assets';

const temporaryDirectories: string[] = [];

afterEach(async () => {
  await Promise.all(temporaryDirectories.splice(0).map(directory => rm(directory, { recursive: true, force: true })));
});

describe('unlicensed public asset guard', () => {
  test('blocks only the exact withheld asset names in the public assets path', () => {
    for (const filename of WITHHELD_PUBLIC_ASSETS) {
      expect(isWithheldPublicAsset(`/assets/${filename}`)).toBe(true);
    }
    expect(isWithheldPublicAsset('/assets/earth-decor.webp?cache=1')).toBe(true);
    expect(isWithheldPublicAsset('/assets/not-earth-decor.webp')).toBe(false);
    expect(isWithheldPublicAsset('/data/earth-decor.webp')).toBe(false);
    expect(isWithheldPublicAsset('/assets/logo.svg')).toBe(false);
    expect(isUnapprovedPublicAsset('/assets/new-photo.png')).toBe(true);
    expect(isUnapprovedPublicAsset('/assets/earth-decor.webp?v=1')).toBe(true);
    expect(isUnapprovedPublicAsset('/favicon.svg')).toBe(false);
    expect(isUnapprovedPublicAsset('/data/earth-decor.webp')).toBe(false);
  });

  test('prunes files copied from public/assets unless they are explicitly approved', async () => {
    const directory = await mkdtemp(join(tmpdir(), 'methane-public-assets-'));
    temporaryDirectories.push(directory);
    const publicAssets = join(directory, 'public', 'assets');
    const outputAssets = join(directory, 'dist', 'assets');
    await mkdir(join(publicAssets, 'unreviewed'), { recursive: true });
    await mkdir(outputAssets, { recursive: true });
    for (const [relativePath, contents] of [
      ['earth-decor.webp', 'withheld'],
      ['unreviewed/new-photo.png', 'unreviewed'],
      ['approved-logo.svg', 'approved'],
    ]) {
      await writeFile(join(publicAssets, relativePath), contents);
      await mkdir(join(outputAssets, relativePath, '..'), { recursive: true });
      await writeFile(join(outputAssets, relativePath), contents);
    }
    await writeFile(join(outputAssets, 'app-hash.js'), 'generated by the app build');

    const removed = await pruneUnapprovedPublicAssets(publicAssets, outputAssets, ['approved-logo.svg']);

    expect(removed.sort()).toEqual(['earth-decor.webp', 'unreviewed/new-photo.png']);
    await expect(readFile(join(outputAssets, 'earth-decor.webp'))).rejects.toMatchObject({ code: 'ENOENT' });
    await expect(readFile(join(outputAssets, 'unreviewed/new-photo.png'))).rejects.toMatchObject({ code: 'ENOENT' });
    expect(await readFile(join(outputAssets, 'approved-logo.svg'), 'utf8')).toBe('approved');
    expect(await readFile(join(outputAssets, 'app-hash.js'), 'utf8')).toBe('generated by the app build');
  });
});
